"""Exports the approved, role-specific handover as a PDF.

The export is built from the same claims the person sees on screen (already filtered by role and
redacted), so it can never contain more than the screen does."""
import re
from datetime import datetime, timezone
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

import handover
import verifier

ACCENT = colors.HexColor("#0F766E")
INK = colors.HexColor("#1F2A37")
GREY = colors.HexColor("#6B7280")
LINE = colors.HexColor("#D1D5DB")


def file_name(case, role):
    def slug(text):
        return re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-") or "handover"
    return f"baton-{slug(case['title'])}-{slug(role)}.pdf"


def document_model(case, role, visible, plan, hidden, redactions, sources, get_chunk, answer_for_claim):
    """Everything that goes into the PDF, as plain data. Tests check this for leaks."""
    usable = [c for c in visible if c["status"] != "Unverified"]

    def lines(claims, show_value=False):
        out = []
        for c in claims:
            if show_value:
                owner, _ = handover.owner_for(c, usable) if c["claim_type"] == "open_task" else (c["value"], False)
                value = owner if verifier.has_value(owner) else "No owner"
                out.append((f'{c["subject"]}: {value}', c["status"]))
            else:
                out.append((c["statement"], c["status"]))
        return out

    def of_type(*types):
        return [c for c in usable if c["claim_type"] in types and c["status"] != "Missing"]

    ask = [c for c in of_type("contact", "owner") if verifier.has_value(c["value"])]
    sections = [
        ("Open work", lines(of_type("open_task"), show_value=True)),
        ("Risks and recurring problems", lines(of_type("risk", "recurring_problem"))),
        ("Who to ask", [(f'{c["subject"]}: {c["value"]}', c["status"]) for c in ask]),
        ("Decisions", lines(of_type("decision"))),
        ("Gaps to fill", lines(handover.unresolved_gaps(usable))),
        ("Dependencies", lines(of_type("dependency"))),
    ]

    evidence = []
    for c in usable:
        if c["status"] == "Missing":
            where, quote = "No source: the information is missing.", ""
        elif c["status"] == "Stated":
            given = answer_for_claim(c["id"])
            who = f'{given["answered_by"]} on {given["created_at"]} UTC' if given else "the person leaving"
            where, quote = f"Stated by {who} (not from a project file).", c["quote"]
        else:
            source = sources.get(c["source_id"])
            chunk_no = c["chunk_index"]
            where = f'{source["filename"]}, chunk {chunk_no}' if source and chunk_no is not None else "Source not recorded"
            quote = c["quote"]
        evidence.append({"statement": c["statement"], "status": c["status"], "where": where, "quote": quote})

    return {
        "title": f'{case["title"]}: handover from {case["leaver"]}',
        "role": role,
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "hidden": hidden,
        "redactions": redactions,
        "plan": [(i, s["text"], s["status"]) for i, s in enumerate(plan, 1)],
        "sections": sections,
        "evidence": evidence,
    }


def model_text(model):
    """All text of the model joined together (used by tests to look for leaks)."""
    parts = [model["title"], model["role"]]
    parts += [t for _, t, _ in model["plan"]]
    for _title, items in model["sections"]:
        parts += [t for t, _ in items]
    for e in model["evidence"]:
        parts += [e["statement"], e["where"], e["quote"]]
    return "\n".join(parts)


def render_pdf(model):
    """Turn the model into PDF bytes."""
    base = ParagraphStyle("base", fontName="Helvetica", fontSize=9.5, leading=13, textColor=INK)
    small = ParagraphStyle("small", parent=base, fontSize=8.2, leading=11, textColor=GREY)
    h1 = ParagraphStyle("h1", parent=base, fontName="Helvetica-Bold", fontSize=18, leading=22, textColor=ACCENT, spaceAfter=4)
    h2 = ParagraphStyle("h2", parent=base, fontName="Helvetica-Bold", fontSize=12, leading=16, textColor=ACCENT, spaceBefore=10, spaceAfter=3)
    item = ParagraphStyle("item", parent=base, leftIndent=10, bulletIndent=0, spaceAfter=2)

    def para(text, style=base):
        return Paragraph(escape(text), style)

    def bullet(text, status):
        return Paragraph(f'{escape(text)} <font color="#6B7280" size="8">[{escape(status)}]</font>', item, bulletText="\u2022")

    story = [
        para(model["title"], h1),
        para("Evidence-linked handover generated by Baton", small),
        Spacer(1, 6),
    ]
    meta = [
        [para("Role", small), para(model["role"], base)],
        [para("Generated", small), para(model["generated"], base)],
        [para("Items hidden for this role", small), para(str(model["hidden"]), base)],
        [para("Details masked for this role", small), para(str(model["redactions"]), base)],
    ]
    table = Table(meta, colWidths=[55 * mm, 110 * mm])
    table.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.5, LINE), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                               ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#E6F4F1"))]))
    story += [table, Spacer(1, 4)]

    story.append(para("Your first-week plan", h2))
    if model["plan"]:
        for i, text, status in model["plan"]:
            story.append(Paragraph(f'{i}. {escape(text)} <font color="#6B7280" size="8">[{escape(status)}]</font>', item))
    else:
        story.append(para("Nothing to plan yet.", base))

    for title, items in model["sections"]:
        story.append(para(title, h2))
        if items:
            story += [bullet(text, status) for text, status in items]
        else:
            story.append(para("None recorded.", base))

    story.append(para("Evidence behind each statement", h2))
    for e in model["evidence"]:
        story.append(Paragraph(f'<b>{escape(e["statement"])}</b> <font color="#6B7280" size="8">[{escape(e["status"])}]</font>', base))
        story.append(para(e["where"], small))
        if e["quote"]:
            story.append(para(f'Quote: {e["quote"]}', small))
        story.append(Spacer(1, 4))

    notes = "Items this role may not see are not listed."
    if model["redactions"]:
        notes += " Emails, phone numbers, amounts and similar details are masked."
    story += [Spacer(1, 6), para(notes, small)]

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(GREY)
        canvas.drawString(18 * mm, 10 * mm, f'Baton | {model["role"]} | generated {model["generated"]}')
        canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
        canvas.restoreState()

    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=16 * mm, bottomMargin=18 * mm, title=model["title"],
                            author="Baton", pageCompression=0)
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buffer.getvalue()


def build_pdf(case, role, visible, plan, hidden, redactions, sources, get_chunk, answer_for_claim):
    model = document_model(case, role, visible, plan, hidden, redactions, sources, get_chunk, answer_for_claim)
    return render_pdf(model)